// ---------------------------------------------------------------------------
// FEELLLM handoff — deterministic Markdown context brief.
// WillULikeIT computes; FEELLLM (or any LLM) explains. The brief carries the
// frozen fit with full provenance and tells the receiving model, explicitly,
// that it must not produce its own liking number or overwrite the fit.
// Same inputs → same brief. No API call, nothing leaves the browser.
// ---------------------------------------------------------------------------

import { attrLabel } from "./vocab";
import { BAND_COPY, reasonLine } from "./fit";
import { VERSIONS, FLOTILLA } from "../versions";
import type { FitResult, JrfSummary } from "./types";

export type BriefQuestion = "why_like" | "least_aligned" | "modify" | "table" | "custom";

export const QUESTIONS: Record<Exclude<BriefQuestion, "custom">, (name: string) => string> = {
  why_like: (n) => `Why might ${n} like — or not like — this?`,
  least_aligned: (n) => `Which part of this is least aligned with ${n}'s preferences, and why does it matter?`,
  modify: (n) => `How could the recipe be modified to raise ${n}'s fit above 85 without losing what makes it itself?`,
  table: () => `Will this suit everyone listed here? Where do their tastes conflict, and what single change would help most people?`
};

const KIND_LABEL: Record<string, string> = {
  expected: "`simulated` — Expected MP6 (MP6-SIM): a prediction, not a measurement",
  observed: "`observed` — an MP6 recorded by a person (MP6-OBS)",
  proxy: "`proxy` — crude unweighted mean of ingredient-level sensory data from the JRF (demo fallback, not an Expected MP6)",
  unknown: "`unknown` — the MP6 file does not state whether it is predicted or observed"
};

const fmt = (n: number) => (Number.isInteger(n) ? String(n) : n.toFixed(1));

export function buildBrief(args: { fits: FitResult[]; jrf?: JrfSummary; question: BriefQuestion; customQuestion?: string }): string {
  const { fits, jrf } = args;
  if (!fits.length) throw new Error("buildBrief needs at least one frozen fit result");
  const lead = fits[0];
  const names = fits.map((f) => f.profileName);
  const who = names.length === 1 ? names[0] : names.slice(0, -1).join(", ") + " and " + names[names.length - 1];
  const q =
    args.question === "custom"
      ? (args.customQuestion ?? "").trim() || QUESTIONS.why_like(who)
      : QUESTIONS[args.question](who);

  const L: string[] = [];
  L.push(`# WillULikeIT → FEELLLM context brief — ${lead.item.name}`);
  L.push("");
  L.push(`Generated by ${VERSIONS.app} (schema \`${VERSIONS.brief}\`) · prediction frozen ${lead.createdAt}`);
  L.push("For use with FEELLLM (feelllm.org) or any LLM. Nothing was sent to a server to produce this brief.");
  L.push("");
  L.push("## How to read this (for the LLM)");
  L.push("- `stated` = the person told us (a preference slider, or a rating of a reference style).");
  L.push("- `simulated` = predicted sensory state (Expected MP6). `observed` = recorded after tasting. Never treat simulated as measured.");
  L.push(`- \`derived\` = computed by WillULikeIT's transparent algorithm \`${lead.algorithmVersion}\`.`);
  L.push("- Every scale is 0–10 on MP6 Product Profile v0.1.1 attributes. An attribute that is absent is UNKNOWN — do not fill it in, and do not treat it as zero.");
  L.push("- The Personal Sensory Fit is an experimental estimate, **not a probability of liking**.");
  L.push("");
  L.push("## Rules for your answer");
  L.push("1. Do **not** produce your own liking score, percentage or verdict number. The fit below is computed deterministically and is frozen; explain it, do not overwrite it.");
  L.push("2. Keep `simulated`, `observed`, `stated` and your own reasoning visibly separate.");
  L.push("3. Treat any recipe change you propose as a hypothesis: it should be re-predicted (new Expected MP6 at record.mp6.app) and then tasted.");
  L.push("4. No health, dietary, allergy or medical advice — this is about taste fit only.");
  L.push("");
  L.push("## The question");
  L.push(`> ${q}`);
  L.push("");

  L.push("## The item");
  L.push(`- Name: **${lead.item.name}**${lead.item.category ? ` (${lead.item.category})` : ""}`);
  L.push(`- Sensory source: ${KIND_LABEL[lead.item.sensoryKind] ?? lead.item.sensoryKind}`);
  if (lead.item.synthetic) L.push("- ⚠ The sensory values are synthetic / reconstructed / fixture data — not panel measurements.");
  if (lead.item.sourceFile) L.push(`- File: \`${lead.item.sourceFile}\``);
  if (jrf) {
    L.push(`- Recipe (JRF): **${jrf.name}**${jrf.version ? ` v${jrf.version}` : ""}${jrf.status ? ` · ${jrf.status}` : ""}`);
    if (jrf.description) L.push(`  - ${jrf.description}`);
    if (jrf.ingredients.length)
      L.push(`  - Ingredients: ${jrf.ingredients.map((i) => `${i.label}${i.quantity !== undefined ? ` ${fmt(i.quantity)}${i.unit ? " " + i.unit : ""}` : ""}`).join("; ")}`);
    if (jrf.processes.length)
      L.push(
        `  - Process: ${jrf.processes
          .map((p) => `${p.label}${p.duration_s ? ` (${humanDuration(p.duration_s)})` : ""}${p.temperature !== undefined ? ` @ ${p.temperature} °C` : ""}`)
          .join(" → ")}`
      );
  }
  L.push("");
  L.push("### Predicted sensory profile `" + (lead.item.sensoryKind === "observed" ? "observed" : "simulated") + "`");
  const sens = Object.entries(lead.sensorySnapshot).sort(([a], [b]) => a.localeCompare(b));
  L.push("| attribute | value /10 |");
  L.push("|---|---|");
  for (const [k, v] of sens) L.push(`| ${attrLabel(k)} (\`${k}\`) | ${fmt(v)} |`);
  L.push("");

  for (const f of fits) {
    L.push(`## ${f.profileName} × ${f.item.name}`);
    L.push(
      f.profileRelation === "other"
        ? `_Profile stated on ${f.profileName}'s behalf by the person using WillULikeIT — a proxy, not ${f.profileName}'s own report._`
        : "_Profile stated by the person themself._"
    );
    L.push("");
    if (f.fit === null) {
      L.push("**Personal Sensory Fit: not computable** — no overlap between stated preferences and the item's sensory attributes. `derived`");
    } else {
      L.push(`**Personal Sensory Fit: ${Math.round(f.fit)} / 100 — ${BAND_COPY[f.band].title}** \`derived\``);
      L.push(`Coverage: ${Math.round(f.coverage * 100)}% of ${f.profileName}'s weighted preferences are described by the item. Weighted mean distance D = ${f.distance} on 0–10.`);
    }
    L.push("");
    L.push("| attribute | stated ideal | item | Δ | importance |");
    L.push("|---|---|---|---|---|");
    for (const c of [...f.compared].sort((a, b) => b.weighted - a.weighted)) {
      L.push(`| ${c.label} | ${fmt(c.user_preference)} | ${fmt(c.predicted)} | ${c.delta > 0 ? "+" : ""}${fmt(c.delta)} | ${c.importance}/3 |`);
    }
    L.push("");
    if (f.matches.length) L.push("Strongest matches `derived`: " + f.matches.slice(0, 4).map((m) => `✓ ${reasonLine(m, f.profileRelation === "other" ? f.profileName : undefined)}`).join(" · "));
    if (f.mismatches.length) L.push("Strongest mismatches `derived`: " + f.mismatches.slice(0, 4).map((m) => `△ ${m.label}: ${reasonLine(m, f.profileRelation === "other" ? f.profileName : undefined)} (${fmt(m.predicted)} vs ${fmt(m.user_preference)})`).join(" · "));
    if (f.notDescribed.length) L.push(`Stated but not described by the item (UNKNOWN, not zero): ${f.notDescribed.map(attrLabel).join(", ")}.`);
    if (f.notInProfile.length) L.push(`Described by the item but no stated preference: ${f.notInProfile.map(attrLabel).join(", ")}.`);
    if (f.context.occasion || f.context.note) L.push(`Context \`stated\`: ${[f.context.occasion, f.context.note].filter(Boolean).join(" — ")}`);
    L.push("");
  }

  L.push("## Provenance");
  L.push("```json");
  L.push(
    JSON.stringify(
      fits.map((f) => ({
        fit_result_id: f.id,
        fit_algorithm: f.algorithmVersion,
        user_profile_version: f.profileVersion,
        user_profile_hash: f.profileHash,
        item_id: f.item.id,
        jrf_hash: f.item.jrfHash ?? null,
        expected_mp6_hash: f.item.expectedMp6Hash ?? null,
        sensory_source_kind: f.item.sensoryKind,
        predicted_fit: f.fit,
        coverage: f.coverage,
        frozen_at: f.createdAt
      })),
      null,
      2
    )
  );
  L.push("```");
  L.push("");
  L.push("## Caveats");
  L.push("- Content-based estimate from one person's stated preferences and one sensory profile. No population data, no collaborative filtering, no calibration yet.");
  L.push("- Liking is not descriptive intensity; a predicted sensory profile can be wrong even when the preference model is right, and vice versa.");
  L.push("- After tasting, the person records actual liking in WillULikeIT; the frozen prediction is never edited.");
  L.push("");
  L.push("---");
  L.push(`WillULikeIT · ${FLOTILLA.jrf.replace("https://", "")} (what is it) · ${FLOTILLA.recorder.replace("https://", "")} (what will it feel like) · willulikeit.org (will you like it) · ${FLOTILLA.feelllm.replace("https://", "")} (why, and what next)`);
  return L.join("\n");
}

function humanDuration(s: number): string {
  if (s >= 86400) return `${fmt(s / 86400)} d`;
  if (s >= 3600) return `${fmt(s / 3600)} h`;
  if (s >= 60) return `${fmt(s / 60)} min`;
  return `${s} s`;
}

export function briefFileName(f: FitResult): string {
  const d = f.createdAt.slice(0, 10);
  return `wulit-brief-${f.item.id}-${f.profileName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${d}.md`;
}
